const definition = (
  dataset: (typeof Dataset)["Type"],
  file: string,
  columns: DuckTable["columns"]
) => {
  const table: DuckTable = {
    name: `tce_rs_${dataset}_${Str.replace(".csv", "")(file)}`,
    key: "__id",
    columns: {
      __id: "VARCHAR",
      __ano: "INTEGER",
      __fonte: "VARCHAR",
      __busca: "VARCHAR",
      ...columns,
    },
    ...(Arr.some(Rec.keys(columns), (column) => /^(?:DS_|NM_|NOME_)/.test(column))
      ? { search: ["__busca"] }
      : {}),
  };
  return { dataset, file, table };
};
