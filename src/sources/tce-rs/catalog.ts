export const tceRsTables = Arr.map(tceRsFiles, (entry) => entry.table);
const TceRsErrorCode = Schema.Literals(["tce-rs.SCOPE", "tce-rs.DOWNLOAD", "tce-rs.PARSE"]);
export class TceRsError extends Schema.TaggedError<TceRsError, { readonly brand: unique symbol }>()(
  "TceRsError",
  { code: TceRsErrorCode }
) {
  override get message() {
    return this.code === "tce-rs.SCOPE"
      ? "Informe entre um e cinco anos válidos para o LicitaCon do TCE-RS."
      : this.code === "tce-rs.PARSE"
        ? "As tabelas ou os cabeçalhos do LicitaCon mudaram; o índice anterior foi preservado."
        : "Falha ao baixar o ZIP anual do LicitaCon do TCE-RS.";
  }
}
